function catalogEntry([id, title, tag, category, source, prompt], index) {
  const num = String(index + 26).padStart(2, "0");
  return q(
    id,
    num,
    title,
    tag,
    category,
    source,
    prompt,
    [`What is in scope for v1?`, `Single-process or distributed?`, `Expected scale / users?`],
    [`Core entities and relationships`, `Main public methods`, `Extensibility / patterns`],
    [`Names domain classes clearly`, `Walks through one happy path`, `Handles at least one edge case`, `Mentions tests or invariants`],
    [id.split("-").join(" "), "class", "interface", "method"],
    [`Main service class for ${title}`, `Enums for fixed domains`],
    `export class ${title.replace(/[^a-zA-Z0-9]/g, "")}Service {\n  // TODO\n}\n`
  );
}

export const LLD_CATALOG_PROBLEMS = CATALOG.map(catalogEntry);
